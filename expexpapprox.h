// Fast exp(exp(x)).
//
//   exp(exp(x)) = 2^w,  w = log2(e) * 2^(x * log2(e))
//
// Each 2^v is evaluated as 2^(m/256) * 2^(r/256) with m = round(256 v) and |r| <= 0.5:
// 2^(m/256) comes from a 256-entry table whose entries already carry the integer part of the
// exponent (added straight into the IEEE-754 exponent bits), 2^(r/256) from a short minimax
// polynomial. m is obtained by adding a large constant, so no libm call is made.
//
// Relative error is about 2e-13 for x in [-36.74, 6.564], dominated by rounding of exp(x)
// being amplified by exp(x). Outside that interval, and for NaN, the result is exact
// (1.0 below, std::exp(std::exp(x)) above).

